/**
 ******************************************************************************
 * @file    board.h
 * @brief   蓝丸(STM32F103C8T6) 两轮差速底盘 —— 板级定义总表
 *
 * 这个文件是"唯一需要改"的地方：换电机、换轮子、改接线，只改这里。
 * 所有常量都带单位，禁止在别处硬编码数值。
 ******************************************************************************
 */
#ifndef __BOARD_H
#define __BOARD_H

#include "stm32f10x.h"

/*==============================================================================
 * 1. 机械与编码器参数  —— 必须用卡尺/实测确认，不能照抄
 *============================================================================*/

/** 轮半径 [m]。直径 125 mm 的轮子 = 0.0625 m */
#define WHEEL_RADIUS_M        0.0625f

/** 输出轴每转脉冲数（四倍频后）。
 *  典型霍尔减速电机：电机轴 11 线 × 4 倍频 = 44，
 *  减速比 1:30 => 1320；取整为 1600 与方案文档里的 encoder_cpr 一致。
 *  !! 换电机必须实测后修改，README 第 4 章有标定方法 */
#define COUNTS_PER_OUT_REV    1600.0f

/** 轮距 [m]，固件只用于差速反解和上报，需实测 */
#define WHEEL_SEPARATION_M    0.330f

/*==============================================================================
 * 2. 控制节拍
 *============================================================================*/

/** 控制循环频率 [Hz]，由 SysTick 触发 */
#define CTRL_TICK_HZ          1000u
/** 控制周期 [s] */
#define CTRL_DT_S             0.001f
/** 测速窗口 [ms]。
 *  1 ms 采样只有 1 个脉冲分辨率，对应约 0.0245 m/s 的量化跳变，噪声太大；
 *  用 10 ms 滑窗把分辨率提高 10 倍，而 PID 仍按 1 kHz 运行不受影响。 */
#define SPEED_WINDOW_MS       10u

/*==============================================================================
 * 3. PWM 与电机
 *============================================================================*/

/** TIM4 自动重装值。TIM4 时钟 72 MHz => 72e6/(3599+1) = 20 kHz */
#define PWM_ARR               3599u
/** 死区补偿：占空比低于该值时电机不转；实测一般 5%~15% 满量程 */
#define MOTOR_DEADBAND        180

/*==============================================================================
 * 4. 底盘限幅
 *============================================================================*/

#define MAX_LINEAR_SPEED_MPS  0.80f   /* 单轮最大线速度 m/s */
#define MAX_ACCEL_MPS2        1.00f   /* 加速度限制 m/s^2 */
#define MAX_DECEL_MPS2        2.00f   /* 减速度限制 m/s^2 */
#define LINK_TIMEOUT_MS       500u    /* 上位机断链保护时间 */

/*==============================================================================
 * 5. 速度环默认参数
 *
 * 这组值是用"一阶惯性 + 真实死区"模型扫出来的（见 tests/host/pid_sweep.c）：
 *   被控对象 K = 0.80 m/s / 3599 CCR，tau = 100 ms，死区 180
 *   Kp=1800 / Ki=20000 在 0.1~0.6 m/s 全速域：
 *     超调 ≈ 0%，稳态误差 ≈ 0，调节时间 0.87 s
 *
 * !! 这仍然是仿真值。实车必须按 README 第 5 章重新整定，
 *    因为真实电机的 tau、死区、负载都跟模型有差距。
 *============================================================================*/

#define PID_KP_DEFAULT        1800.0f
#define PID_KI_DEFAULT       20000.0f
#define PID_KD_DEFAULT           0.0f
#define PID_OUT_LIMIT         ((float)PWM_ARR)

/*==============================================================================
 * 6. 引脚分配（与 README 接线表一一对应）
 *============================================================================*/

/* 左编码器 TIM2_CH1/CH2 —— PA0/PA1（FT 脚，5V 容忍） */
#define ENC_L_PORT            GPIOA
#define ENC_L_PINS            (GPIO_Pin_0 | GPIO_Pin_1)

/* 右编码器 TIM3_CH1/CH2 —— PA6/PA7 */
#define ENC_R_PORT            GPIOA
#define ENC_R_PINS            (GPIO_Pin_6 | GPIO_Pin_7)

/* 电机 PWM：TIM4_CH1 = PB6(左)，TIM4_CH2 = PB7(右) */
#define PWM_L_CCR             (TIM4->CCR1)
#define PWM_R_CCR             (TIM4->CCR2)

/* TB6612 方向与使能 */
#define TB_PORT               GPIOB
#define TB_STBY_PIN           GPIO_Pin_11
#define TB_AIN1_PIN           GPIO_Pin_12   /* 左 IN1 */
#define TB_AIN2_PIN           GPIO_Pin_13   /* 左 IN2 */
#define TB_BIN1_PIN           GPIO_Pin_14   /* 右 IN1 */
#define TB_BIN2_PIN           GPIO_Pin_15   /* 右 IN2 */

/* 板载 LED：PC13，低电平点亮 */
#define LED_PORT              GPIOC
#define LED_PIN               GPIO_Pin_13

/* 调试串口 USART1：PA9=TX  PA10=RX */
#define DBG_BAUDRATE          115200u
#define USART1_TX_PORT        GPIOA
#define USART1_RX_PORT        GPIOA

/*==============================================================================
 * 7. 工具宏
 *============================================================================*/

#define ARRAY_LEN(a)          (sizeof(a) / sizeof((a)[0]))

#ifndef M_PI
#define M_PI                  3.14159265358979f
#endif

/** 每个编码器脉冲对应的轮面位移 [m/count] */
#define METERS_PER_COUNT      (2.0f * M_PI * WHEEL_RADIUS_M / COUNTS_PER_OUT_REV)

#endif /* __BOARD_H */
